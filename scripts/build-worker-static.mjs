// Embeds public/ into the Worker bundle (Workers have no file system). Binary files are base64.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const TYPES = {
  html: 'text/html; charset=utf-8', css: 'text/css; charset=utf-8', js: 'text/javascript; charset=utf-8',
  webmanifest: 'application/manifest+json', json: 'application/json', svg: 'image/svg+xml', png: 'image/png', ico: 'image/x-icon',
}
const BINARY = new Set(['png', 'ico'])
const files = {}
function walk(dir, prefix) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) { walk(full, `${prefix}${name}/`); continue }
    const ext = name.split('.').pop()
    if (!TYPES[ext]) continue
    files[`/${prefix}${name}`] = BINARY.has(ext)
      ? { type: TYPES[ext], base64: readFileSync(full).toString('base64') }
      : { type: TYPES[ext], body: readFileSync(full, 'utf8') }
  }
}
walk('public', '')
writeFileSync('worker/static-files.gen.js', `// Generated by scripts/build-worker-static.mjs. Do not edit.\nexport default ${JSON.stringify(files)}\n`)
console.log(`Embedded ${Object.keys(files).length} files`)
