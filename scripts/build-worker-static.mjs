// Embeds public/ into the Worker bundle (Workers have no file system).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const TYPES = { html: 'text/html; charset=utf-8', css: 'text/css; charset=utf-8', js: 'text/javascript; charset=utf-8' }
const files = {}
for (const name of readdirSync('public')) {
  const ext = name.split('.').pop()
  if (!TYPES[ext]) continue
  files[`/${name}`] = { type: TYPES[ext], body: readFileSync(`public/${name}`, 'utf8') }
}
writeFileSync('worker/static-files.gen.js', `// Generated by scripts/build-worker-static.mjs. Do not edit.\nexport default ${JSON.stringify(files)}\n`)
console.log(`Embedded ${Object.keys(files).length} files`)
